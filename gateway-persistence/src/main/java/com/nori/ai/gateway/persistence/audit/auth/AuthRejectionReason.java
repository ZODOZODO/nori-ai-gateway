package com.nori.ai.gateway.persistence.audit.auth;

public enum AuthRejectionReason {
    SERVICE_TOKEN_MISSING(401), SERVICE_TOKEN_INVALID(401), ACTOR_ASSERTION_MISSING(401),
    SIGNATURE_INVALID(401), UNKNOWN_KID(401), ALGORITHM_NOT_ALLOWED(401), UNTRUSTED_KEY_REFERENCE(401),
    ISSUER_INVALID(401), AUDIENCE_INVALID(401), ASSERTION_TIME_INVALID(401), ASSERTION_EXPIRED(401),
    ASSERTION_LIFETIME_INVALID(401), SUBJECT_INVALID(401), READ_SCOPE_INVALID(401), PERMISSIONS_INVALID(401),
    PDG_MISSING(401), PDG_INVALID(401), DELEGATION_INVALID(401), DELEGATION_FORBIDDEN(401), SYSTEM_SCOPE_MISMATCH(403);

    private final int httpStatus;
    AuthRejectionReason(int httpStatus) { this.httpStatus = httpStatus; }
    public int httpStatus() { return httpStatus; }
}
